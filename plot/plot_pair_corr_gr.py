#!/usr/bin/env python3
"""Reconstruct real-space LLL pair correlations from fermion4_2rdm.csv.

Required input columns: a,b,c,d,re,im (1-based spin orbital modes).
Gamma[a,b;c,d] = <c†_a c†_b c_d c_c> for a<b,c<d, upper Hermitian pair triangle.

Using Landau-gauge orbitals phi_j(x,y) = exp(-(x-Xj)^2/2 + i*kj*y) / (pi**1/4 sqrt(Ly)),
Xj=(j-1/2)*sqrt(2*pi*gamma/N), kj=(j-1)*2*pi/Ly, lB=1.
The global momentum offset does not affect the local density correlation.

rho2(r;r1) = < :rho(r) rho(r1): >
  = sum_{sigma,sigma'} sum_{abcd} phi_a*(r)phi_b*(r1)
      phi_d(r1)phi_c(r) Gamma[a,b;c,d]  (all ORDERED spin orbitals).
We reconstruct all ordered terms from the canonical antisymmetric Gamma.
"""
import argparse
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

plt.rcParams.update({
    "font.family": "STIXGeneral",
    "mathtext.fontset": "stix",
    "font.size": 15,
    "axes.labelsize": 17,
    "xtick.labelsize": 13,
    "ytick.labelsize": 13,
})


def get_config(folder):
    conf = folder / "config.txt"
    result = {}
    if conf.is_file():
        for line in conf.read_text(encoding="utf-8").splitlines():
            lhs, sep, rhs = line.partition("=")
            if sep:
                result[lhs.strip()] = rhs.split("#", 1)[0].strip()
    return result


def validate_rows(df, n):
    needed = {"a", "b", "c", "d", "re", "im"}
    missing = needed - set(df.columns)
    if missing:
        raise ValueError(f"Missing columns: {sorted(missing)}")
    if df.empty:
        raise ValueError("Empty 2-RDM CSV")
    ids = df[["a", "b", "c", "d"]].to_numpy(dtype=np.int64)
    if ((ids < 1) | (ids > 2 * n)).any():
        raise ValueError("Spin-orbital mode index outside 1..2*N")
    if not ((ids[:, 0] < ids[:, 1]) & (ids[:, 2] < ids[:, 3])).all():
        raise ValueError("Expected canonical fermion pair indices a<b and c<d")
    g1 = (ids[:, 0] - 1)//2 + (ids[:, 1] - 1)//2
    g2 = (ids[:, 2] - 1)//2 + (ids[:, 3] - 1)//2
    if "G_pair" in df.columns and (df["G_pair"] >= n).any():
        # In edge mode G extends beyond N, so G_pair values >= N are valid.
        pass
    sz1 = (1 - 2*(ids[:, 0] % 2 == 0).astype(int)) + (1 - 2*(ids[:, 1] % 2 == 0).astype(int))
    sz2 = (1 - 2*(ids[:, 2] % 2 == 0).astype(int)) + (1 - 2*(ids[:, 3] % 2 == 0).astype(int))
    if not np.array_equal(sz1, sz2):
        raise ValueError("Pair spin is not conserved in the CSV")
    # The intended use is the open cylinder (exact sum). Torus input is not
    # currently supported by this cylinder real-space reconstruction.
    if not np.array_equal(g1, g2):
        raise ValueError("Pair orbital momentum not conserved exactly; this script expects system='edge'")
    if not np.isfinite(df[["re", "im"]].to_numpy(dtype=float)).all():
        raise ValueError("NaN or infinite 2-RDM element")
    if df.duplicated(["a", "b", "c", "d"]).any():
        raise ValueError("Repeated 2-RDM pair element")


def make_orbital(n, gamma, x, y):
    delta = np.sqrt(2 * np.pi * gamma / n)
    X = (np.arange(n) + 0.5) * delta
    Ly = 2 * np.pi / delta
    k = np.arange(n) * (2 * np.pi / Ly)
    # x and y are scalar or arrays, broadcasting handled by caller.
    return np.exp(-0.5 * (x - X)**2 + 1j * k * y) / (np.pi**0.25 * np.sqrt(Ly))


def coefficient_matrix(df, n, gamma, x1, y1, channel="total"):
    """Construct A_uv so rho2(r;r1) = sum_uv A_uv phi_u*(r) phi_v(r)."""
    if channel not in {"total", "upup", "updn", "dnup", "dndn"}:
        raise ValueError("Unknown channel")

    phi1 = make_orbital(n, gamma, x1, y1)
    A = np.zeros((n, n), dtype=complex)
    channels = {
        "upup": (1, 1), "updn": (1, -1),
        "dnup": (-1, 1), "dndn": (-1, -1),
    }
    requested = channels.get(channel)

    def add_term(x, y, z, w, weight):
        # F_xy(r) F_zw(r1) with F_xy=phi_x*phi_y, spin selection.
        spin_r = 1 if x % 2 else -1
        spin_r_other = 1 if y % 2 else -1
        spin_ref = 1 if z % 2 else -1
        spin_ref_other = 1 if w % 2 else -1
        if spin_r != spin_r_other or spin_ref != spin_ref_other:
            return
        if requested is not None and requested != (spin_r, spin_ref):
            return
        ix, iy, iz, iw = ((mode-1)//2 for mode in (x, y, z, w))
        A[ix, iy] += weight * np.conj(phi1[iz]) * phi1[iw]

    def accumulate(a, b, c, d, val):
        # Four ordered operator index assignments generated by fermionic antisymmetry:
        # +F_ac(r)F_bd(r1) -F_bc(r)F_ad(r1)
        # -F_ad(r)F_bc(r1) +F_bd(r)F_ac(r1)
        add_term(a, c, b, d,  val)
        add_term(b, c, a, d, -val)
        add_term(a, d, b, c, -val)
        add_term(b, d, a, c,  val)

    for a,b,c,d,re,im in df[["a","b","c","d","re","im"]].itertuples(index=False, name=None):
        a,b,c,d = int(a),int(b),int(c),int(d)
        value = complex(re, im)
        accumulate(a,b,c,d,value)
        if (a,b) != (c,d):
            accumulate(c,d,a,b,np.conj(value))

    return A


def evaluate_map(A, n, gamma, x_axis, y_axis):
    delta = np.sqrt(2*np.pi*gamma/n)
    Ly = 2*np.pi/delta
    X = (np.arange(n) + 0.5)*delta
    # 1/sqrt(pi)/Ly comes from conjugate(phi_i) * phi_j.
    envelopes = np.exp(-0.5 * (x_axis[None,:]-X[:,None])**2) / (np.pi**0.25*np.sqrt(Ly))
    qq = np.arange(-(n-1),n)
    harmonics = np.zeros((len(qq), len(x_axis)), dtype=complex)
    for t,q in enumerate(qq):
        iu = np.arange(max(0,-q), min(n,n-q))
        iv = iu + q
        if len(iu):
            harmonics[t] = np.einsum("i,ix,ix->x", A[iu,iv],envelopes[iu],envelopes[iv], optimize=True)
    phases = np.exp(1j * 2*np.pi/Ly * y_axis[:,None] * qq[None,:])
    pair_density = phases @ harmonics
    imag_error = np.max(np.abs(pair_density.imag))
    if imag_error > 1e-7:
        print(f"WARNING: Imaginary part of pair-density map: {imag_error:.3e}")
    return pair_density.real, Ly


def reference_density(occ_path, n, gamma, x1, y1):
    if not occ_path.is_file():
        raise FileNotFoundError(f"Need occupations at {occ_path} for conditional normalization")
    occ = pd.read_csv(occ_path)
    occ = occ[occ["j"] >= 1].sort_values("j")
    if not np.array_equal(occ["j"].to_numpy(),np.arange(1,n+1)):
        raise ValueError("orb_occ_exp.csv must contain j=1..N")
    phi1 = make_orbital(n,gamma,x1,y1)
    return float(np.dot(occ["ntot"].to_numpy(),np.abs(phi1)**2))


def main():
    parser = argparse.ArgumentParser(description="Pair correlation from selected 4-fermion 2-RDM entries")
    parser.add_argument("csv",type=Path,help="fermion4_2rdm.csv")
    parser.add_argument("--n",type=int,default=None,help="Number of orbital sites (or read config.txt)")
    parser.add_argument("--gamma",type=float,default=None,help="Aspect gamma=Lx/Ly (or read config.txt)")
    parser.add_argument("--x1",type=float,default=None,help="Reference x/lB, default Lx/2")
    parser.add_argument("--y1",type=float,default=None,help="Reference y/lB, default Ly/2")
    parser.add_argument("--xrange",type=float,nargs=2,default=None,metavar=("XMIN","XMAX"))
    parser.add_argument("--yrange",type=float,nargs=2,default=None,metavar=("YMIN","YMAX"))
    parser.add_argument("--nx",type=int,default=300)
    parser.add_argument("--ny",type=int,default=180)
    parser.add_argument("--channel",choices=("total","upup","updn","dnup","dndn"),default="total")
    parser.add_argument("--normalization",choices=("g","rho2","conditional"),default="g",
                        help="g=rho2/rho0^2, rho2=unscaled, conditional=rho2/[rho(r1)*rho0]")
    parser.add_argument("--nu",type=float,default=1/3,help="Reference bulk filling for normalization")
    parser.add_argument("--orb-occ",type=Path,default=None)
    parser.add_argument("--out",type=Path,default=None,help="Output file prefix, without extension")
    args=parser.parse_args()
    conf=get_config(args.csv.parent)
    n=args.n if args.n is not None else int(conf["N"]) if "N" in conf else None
    gamma=args.gamma if args.gamma is not None else float(conf["aspect"]) if "aspect" in conf else None
    if n is None or gamma is None:
        parser.error("Specify --n and --gamma, or put config.txt next to 2-RDM CSV")
    if n<2 or gamma<=0 or args.nu<=0 or args.nx<2 or args.ny<2:
        parser.error("Require n>=2, gamma>0, nu>0, nx>=2, ny>=2")
    delta=np.sqrt(2*np.pi*gamma/n)
    Lx=n*delta
    Ly=2*np.pi/delta
    x1=args.x1 if args.x1 is not None else Lx/2
    y1=args.y1 if args.y1 is not None else Ly/2
    xlo,xhi=args.xrange if args.xrange is not None else (0.,Lx)
    ylo,yhi=args.yrange if args.yrange is not None else (0.,Ly)
    if xlo>=xhi or ylo>=yhi:
        parser.error("Invalid coordinate range")
    xaxis=np.linspace(xlo,xhi,args.nx)
    yaxis=np.linspace(ylo,yhi,args.ny)
    df=pd.read_csv(args.csv)
    validate_rows(df,n)
    print(f"Read {len(df):,} canonical 2-RDM entries, N={n}, gamma={gamma}, Lx={Lx:.4f}, Ly={Ly:.4f}")
    A=coefficient_matrix(df,n,gamma,x1,y1,channel=args.channel)
    herm_error=np.max(np.abs(A-A.conj().T))
    print(f"Coefficient hermiticity error: {herm_error:.3e}")
    result,Ly=evaluate_map(A,n,gamma,xaxis,yaxis)
    rho0=args.nu/(2*np.pi)
    if args.normalization=="g":
        result/=rho0**2
        cbar_label=r"$g(\mathbf{r};\mathbf{r}_1)$"
    elif args.normalization=="conditional":
        occ_path=args.orb_occ if args.orb_occ is not None else args.csv.parent/"orb_occ_exp.csv"
        rho1=reference_density(occ_path,n,gamma,x1,y1)
        if rho1<=0: raise ValueError("Reference density is zero")
        result/=(rho1*rho0)
        cbar_label=r"$\rho^{(2)}/[\rho(\mathbf{r}_1)\rho_0]$"
    else:
        cbar_label=r"$\rho^{(2)}(\mathbf{r},\mathbf{r}_1)\ell_B^4$"

    outprefix=args.out if args.out is not None else args.csv.parent/f"paircorr_{args.channel}_{args.normalization}"
    outprefix.parent.mkdir(parents=True,exist_ok=True)
    fig, ax=plt.subplots(figsize=(8.5,5.6))
    im=ax.imshow(result,origin="lower",extent=(xlo,xhi,ylo,yhi),
                 aspect="equal",cmap="Purples",interpolation="nearest")
    ax.scatter([x1],[y1],marker="x",s=65,color="tab:orange",linewidths=1.8,label=r"$\mathbf{r}_1$")
    ax.set_xlabel(r"$x/\ell_B$")
    ax.set_ylabel(r"$y/\ell_B$")
    ax.legend(frameon=False,loc="upper right")
    cb=fig.colorbar(im,ax=ax,pad=0.025)
    cb.set_label(cbar_label)
    fig.tight_layout()
    for ext in ("png","pdf"):
        outfile=Path(f"{outprefix}.{ext}")
        fig.savefig(outfile,dpi=300,bbox_inches="tight")
        print(f"Saved: {outfile}")
    plt.close(fig)
    print(f"Reconstructed range: [{result.min():.6g}, {result.max():.6g}]")
    print("WARNING: If input 2-RDM uses anchor_radius/max_transfer cutoffs, this is an approximation.")


if __name__=="__main__":
    main()
